/**
 * Emits resources/scss/_icons.generated.scss containing only the Bootstrap
 * Icons this project actually references.
 *
 * The full icon stylesheet defines ~2050 classes; FurniCraft uses a few dozen.
 * Shipping all of them was most of the CSS payload.
 *
 * Icon names are read from Blade, JS and PHP, because the admin sidebar,
 * dashboard tiles and settings tabs name their icons in PHP arrays.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const SCAN_DIRS = ['resources/views', 'resources/js', 'app', 'database/seeders'];
const SCAN_EXTENSIONS = new Set(['.php', '.js', '.blade', '.mjs']);

async function* walk(dir) {
    let entries;
    try {
        entries = await readdir(dir, { withFileTypes: true });
    } catch {
        return;
    }

    for (const entry of entries) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) {
            yield* walk(full);
        } else if (SCAN_EXTENSIONS.has(extname(entry.name)) || entry.name.endsWith('.blade.php')) {
            yield full;
        }
    }
}

const used = new Set();
// Matches "bi-chevron-right" wherever it appears, including inside a PHP string.
const pattern = /\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g;

for (const dir of SCAN_DIRS) {
    for await (const file of walk(resolve(root, dir))) {
        const source = await readFile(file, 'utf8');
        let match;
        while ((match = pattern.exec(source)) !== null) {
            used.add(match[1]);
        }
    }
}

const iconsJsonPath = resolve(root, 'node_modules/bootstrap-icons/font/bootstrap-icons.json');
const icons = JSON.parse(await readFile(iconsJsonPath, 'utf8'));

const known = [...used].filter((name) => Object.hasOwn(icons, name)).sort();
const unknown = [...used].filter((name) => !Object.hasOwn(icons, name)).sort();

// No cache-busting query on the font URL: the layouts preload this exact
// path, and a mismatched query string would fetch the font twice.
const suffix = '';

const rules = known
    .map((name) => `.bi-${name}::before { content: "\\${icons[name].toString(16)}"; }`)
    .join('\n');

const output = `// GENERATED by build/generate-icons.mjs — do not edit.
// ${known.length} of ${Object.keys(icons).length} Bootstrap Icons, matching what this project uses.
// Run "npm run icons" (or "npm run build") after adding a new icon.

@font-face {
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("./fonts/bootstrap-icons.woff2${suffix}") format("woff2"),
       url("./fonts/bootstrap-icons.woff${suffix}") format("woff");
}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
  display: inline-block;
  font-family: "bootstrap-icons" !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules}
`;

await writeFile(resolve(root, 'resources/scss/_icons.generated.scss'), output);

console.log(`icons: kept ${known.length} of ${Object.keys(icons).length}`);

if (unknown.length) {
    console.warn(`icons: ${unknown.length} name(s) not in Bootstrap Icons, ignored: ${unknown.join(', ')}`);
}
